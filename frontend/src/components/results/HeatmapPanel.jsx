import { useState } from "react";
import { Layers } from "lucide-react";
import Card from "../Card";
import SegmentedControl from "../SegmentedControl";
import "../../styles/results/heatmap-panel.css";

const CONDITION_LABELS = { cataract: "Cataract", glaucoma: "Glaucoma" };

function HeatmapPanel({ conditions, photoUrl }) {
  const [selected, setSelected] = useState(conditions[0].condition);

  const current = conditions.find((item) => item.condition === selected);
  const options = conditions.map((item) => ({
    value: item.condition,
    label: CONDITION_LABELS[item.condition],
  }));

  return (
    <Card
      title="Heatmap (Grad-CAM)"
      aside={
        <SegmentedControl
          label="Heatmap condition"
          options={options}
          value={selected}
          onChange={setSelected}
        />
      }
    >
      <div
        className={`heatmap-panel__canvas ${
          current.heatmap_url ? "" : "heatmap-panel__canvas--empty"
        }`}
      >
        {current.heatmap_url ? (
          <img
            className="heatmap-panel__image"
            src={current.heatmap_url}
            alt={`${CONDITION_LABELS[selected]} heatmap overlaid on the fundus photo`}
          />
        ) : (
          <div className="heatmap-panel__placeholder">
            <Layers size={24} aria-hidden="true" />
            <p className="body-md">Heatmap overlay generated by the model</p>
          </div>
        )}

        {photoUrl && (
          <div className="heatmap-panel__photo">
            <img
              className="heatmap-panel__thumb"
              src={photoUrl}
              alt="Original fundus photo"
            />
            <div>
              <p className="heatmap-panel__photo-label label-mono">
                Original photo
              </p>
              <p className="mono-meta">512 × 512</p>
            </div>
          </div>
        )}
      </div>

      <p className="heatmap-panel__caption body-md">
        Shows which parts of the photo most influenced this score. It does not
        show where disease is. For cataract this is supporting evidence only.
      </p>
    </Card>
  );
}

export default HeatmapPanel;
